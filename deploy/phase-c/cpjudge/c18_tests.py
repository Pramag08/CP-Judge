 def test_inventory_conflict_blocks_cutover_then_rollback_retains_intervening_data(self):
  user,pw=self.make();missing=U.objects.create_user('legacy-missing',password='Existing-pw-31!')
  old={u.pk:u.password for u in U.objects.all()}
  staged=stage_keys(self.admin);self.assertEqual(staged['unresolved'],1)
