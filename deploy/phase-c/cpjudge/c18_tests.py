 def race(self,fn):
  barrier=Barrier(2)
  def run(i):
   close_old_connections()
   try:
    barrier.wait(timeout=10)
    try:fn(i);return 'ok'
    except IntegrityError:return 'collision'
   finally:close_old_connections()
  with ThreadPoolExecutor(2) as pool:result=list(pool.map(run,range(2)))
  self.assertCountEqual(result,['ok','collision'])
